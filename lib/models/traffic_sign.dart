/// 通用交通标志类型（停车模式专用符号）。
///
/// 为什么不用车模当图标：
/// 1. 章节图标原本是「本章目标车」的车模 PNG，而一章 36 关全是同一款车
///    —— 第 1 章打开就是 36 辆一模一样的自行车，是纯粹的视觉噪音。
/// 2. 想让图标有变化就得贴后面章节的车，等于**提前把玩家还没解锁的车亮出来**，
///    破坏图鉴的收藏惊喜。
///
/// 交通标志两头都躲开：语言无关（不占 arb）、不剧透任何车型，
/// 而真实路牌本来就有一套「环境符号」，能表达章节主题（城区/铁路/港口/太空）。
///
/// **选型约束：字形必须够粗**。标志在关卡格子里只有 19px，
/// 细密的图形（环岛小箭头、合流双线）会糊成一个问号；
/// 只保留「一个粗笔画元素」的符号（P、箭头、感叹号、X、锚、圆环）。
///
/// 图形与面板形状在 `lib/widgets/traffic_sign.dart`，本枚举只描述语义，
/// 保持零依赖（数据管线也会 import 它）。
enum TrafficSignKind {
  /// 停车（P）。停车模式的通用标识，关卡格子全部用它。
  parking,

  /// 红绿灯：城区路口、车流。
  trafficLight,

  /// 连续弯道：小巷、窄路。
  turn,

  /// 交叉（X）：铁道路口、编组站。
  crossing,

  /// 直行：跑道、真空管道。
  straight,

  /// 上坡/发射：坡道、发射台、航天。
  ramp,

  /// 下坡/进场：陡降、滑翔。
  glide,

  /// 下行/地下：地铁、地下管道。
  tunnel,

  /// 锚地：码头、港区。
  anchor,

  /// 工业园区：厂区、货运枢纽。
  factory,

  /// 注意危险：重载干线、管制区。
  warning,

  /// 禁止通行：军事管制、禁区。
  noEntry,

  /// 环轨：轨道、空间站、反重力区。
  orbit,
}
